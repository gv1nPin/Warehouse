from abc import ABC, abstractmethod

from warehouse.dal.unit_of_work import UnitOfWork


class AbstractShipmentTransitCoordinator(ABC):
    """Что происходит с перевозкой после приёмки этапа.

    Транзакцию не открывает: uow передаёт тот, кто вызывает. Из web напрямую
    не вызывается — это внутренний шаг приёмки:

        with self.uow_factory() as uow:
            ...приняли этап...
            self.transit.after_stage_accepted(uow, stage_id)
    """

    @abstractmethod
    def after_stage_accepted(self, uow: UnitOfWork, stage_id: int) -> None:
        """Двигает перевозку дальше по маршруту.

        Есть следующий этап -> переносит в него принятые количества,
        резервирует их на транзитном складе и ставит этап в «Зарезервировано».
        Следующего этапа нет -> закрывает перевозку.

        Вызывать ПОСЛЕ того, как этап получил финальный статус
        («Принято» или «Принято с расхождениями») и остатки оприходованы:
        финальный статус перевозки считается по статусам её этапов,
        а резерв берётся из уже начисленного остатка.
        """
